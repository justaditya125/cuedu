#!/usr/bin/env python3
"""Export the results SQLite database as a MySQL-loadable .sql file.

    python3 scripts/export-mysql.py exam-data/results.db exam-data/results-mysql.sql

Load it on the server with the MySQL client (as an account that may create tables):

    mysql cuedu_results < results-mysql.sql

Values are copied exactly as stored - this only changes the container.

The file is safe to re-run for each result release. It builds complete new
tables beside the live ones and swaps them in with a single RENAME TABLE, which
MySQL performs atomically, so a student looking up a result during the load sees
either the whole old release or the whole new one, never a mix. Tables carry an
exam_ prefix so they cannot collide with anything else in a shared database.
"""
import os
import sqlite3
import sys

TABLES = ["exam_batches", "exam_students", "exam_subjects", "exam_reattempts"]
BATCH_ROWS = 200

# (sqlite table, mysql table, columns)
COLUMNS = {
    "batches": ["id", "kind", "source_file", "program", "semester", "exam_month", "batch",
                "sheet_title", "institution", "imported_at"],
    "students": ["id", "batch_id", "sl_no", "enrollment_no", "name", "total_grade_point",
                 "total_credit_point", "sgpa", "final_result"],
    "subjects": ["id", "student_id", "position", "subject_name", "credit", "internal", "external",
                 "total", "grade", "grade_point", "credit_point"],
    "reattempts": ["id", "batch_id", "university", "enrollment_no", "lead_id", "admission_batch",
                   "student_name", "course", "specialisation", "semester", "subject_name",
                   "exam_type", "internal", "external", "total", "result"],
}

# Text columns are VARCHAR(255) - wide enough for every value in the sheets, and
# the export refuses to run if a value would not fit rather than letting MySQL
# truncate it. Integers stay integers.
INT_COLS = {"id", "batch_id", "student_id", "position"}
WIDTH = 255

DDL = """CREATE TABLE {t}_new (
  id INT UNSIGNED NOT NULL,
  kind VARCHAR(16) NOT NULL,
  source_file VARCHAR(255) NOT NULL,
  program VARCHAR(255),
  semester INT,
  exam_month VARCHAR(32),
  batch VARCHAR(64),
  sheet_title VARCHAR(255),
  institution VARCHAR(255),
  imported_at VARCHAR(32) NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;""", """CREATE TABLE {t}_new (
  id INT UNSIGNED NOT NULL,
  batch_id INT UNSIGNED NOT NULL,
  sl_no VARCHAR(255),
  enrollment_no VARCHAR(64) NOT NULL,
  name VARCHAR(255),
  total_grade_point VARCHAR(255),
  total_credit_point VARCHAR(255),
  sgpa VARCHAR(255),
  final_result VARCHAR(255),
  PRIMARY KEY (id),
  KEY idx_enrollment (enrollment_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;""", """CREATE TABLE {t}_new (
  id INT UNSIGNED NOT NULL,
  student_id INT UNSIGNED NOT NULL,
  position INT NOT NULL,
  subject_name VARCHAR(255),
  credit VARCHAR(255),
  internal VARCHAR(255),
  external VARCHAR(255),
  total VARCHAR(255),
  grade VARCHAR(255),
  grade_point VARCHAR(255),
  credit_point VARCHAR(255),
  PRIMARY KEY (id),
  KEY idx_student (student_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;""", """CREATE TABLE {t}_new (
  id INT UNSIGNED NOT NULL,
  batch_id INT UNSIGNED NOT NULL,
  university VARCHAR(255),
  enrollment_no VARCHAR(64) NOT NULL,
  lead_id VARCHAR(255),
  admission_batch VARCHAR(255),
  student_name VARCHAR(255),
  course VARCHAR(255),
  specialisation VARCHAR(255),
  semester VARCHAR(255),
  subject_name VARCHAR(255),
  exam_type VARCHAR(255),
  internal VARCHAR(255),
  external VARCHAR(255),
  total VARCHAR(255),
  result VARCHAR(255),
  PRIMARY KEY (id),
  KEY idx_enrollment (enrollment_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;"""


def quote(v, col):
    """A SQL literal. Strings are escaped for the default (backslash-escaping) mode."""
    if v is None:
        return "NULL"
    if col in INT_COLS or (col == "semester" and isinstance(v, int)):
        return str(int(v))
    s = str(v)
    if len(s) > WIDTH:
        sys.exit("value in column %r is %d characters, longer than the %d the table allows: %r"
                 % (col, len(s), WIDTH, s[:60]))
    s = (s.replace("\\", "\\\\").replace("'", "''").replace("\0", "\\0")
          .replace("\n", "\\n").replace("\r", "\\r").replace("\x1a", "\\Z"))
    return "'" + s + "'"


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: export-mysql.py <results.db> <output .sql>")
    src, out = sys.argv[1], sys.argv[2]
    db = sqlite3.connect("file:%s?mode=ro" % src, uri=True)

    out_lines = []
    emit = out_lines.append
    emit("-- Exam results - generated by scripts/export-mysql.py. Contains student data: do not commit or share.")
    emit("-- Safe to re-run: builds *_new tables, then swaps them in atomically.")
    emit("SET NAMES utf8mb4;")
    emit("")
    emit("DROP TABLE IF EXISTS %s;" % ", ".join(t + "_new" for t in TABLES))
    emit("")

    counts = {}
    for (sqlite_t, cols), mysql_t, ddl in zip(COLUMNS.items(), TABLES, DDL):
        emit(ddl.format(t=mysql_t))
        rows = db.execute("SELECT %s FROM %s ORDER BY id" % (", ".join(cols), sqlite_t)).fetchall()
        counts[mysql_t] = len(rows)
        for i in range(0, len(rows), BATCH_ROWS):
            chunk = rows[i:i + BATCH_ROWS]
            values = ",\n".join("(" + ", ".join(quote(v, c) for v, c in zip(r, cols)) + ")" for r in chunk)
            emit("INSERT INTO %s_new (%s) VALUES\n%s;" % (mysql_t, ", ".join(cols), values))
        emit("")

    emit("-- Make sure the live tables exist (first run), then swap all four in one atomic statement.")
    for t in TABLES:
        emit("CREATE TABLE IF NOT EXISTS %s LIKE %s_new;" % (t, t))
    emit("RENAME TABLE")
    emit(",\n".join("  %s TO %s_old, %s_new TO %s" % (t, t, t, t) for t in TABLES) + ";")
    emit("DROP TABLE %s;" % ", ".join(t + "_old" for t in TABLES))
    emit("")
    emit("-- What is now live:")
    emit(" UNION ALL ".join("SELECT '%s' AS table_name, COUNT(*) AS `rows` FROM %s" % (t, t) for t in TABLES) + ";")

    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(out_lines) + "\n")
    os.chmod(out, 0o600)
    print("wrote %s" % out)
    for t, n in counts.items():
        print("  %-16s %5d rows" % (t, n))


if __name__ == "__main__":
    main()
